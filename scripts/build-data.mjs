import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";

const [categoryFiles, humansFile] = await Promise.all([
  readdir("messages", { withFileTypes: true }),
  readFile("public/humans.txt", "utf8"),
]);

const defaultNames = [
  "Ali", "Andy", "April", "Brannon", "Chris", "Cord", "Dan", "Darren",
  "David", "Edy", "Ethan", "Fanny", "Gabe", "Ganesh", "Greg", "Guillaume",
  "James", "Jason", "Jay", "Jen", "John", "Kelan", "Kim", "Lauren", "Marcus",
  "Matt", "Matthias", "Mattie", "Mike", "Nate", "Nick", "Pasha", "Patrick",
  "Paul", "Preston", "Qi", "Rachel", "Rainer", "Randal", "Ryan", "Sarah",
  "Stephen", "Steve", "Steven", "Sunakshi", "Todd", "Tom", "Tony",
];

const categoryNames = categoryFiles
  .filter((file) => file.isFile() && file.name.endsWith(".txt"))
  .map((file) => file.name.slice(0, -4))
  .sort();

if (!categoryNames.includes("legacy")) {
  throw new Error("messages/legacy.txt is required to preserve existing permalink hashes.");
}

const messagesByCategory = Object.fromEntries(await Promise.all(categoryNames.map(async (category) => {
  const content = await readFile(`messages/${category}.txt`, "utf8");
  const messages = content.match(/[^\n]*(?:\n|$)/g)
    .filter((line) => line.length > 0)
    .map((line) => ({
      hash: createHash("md5").update(line, "utf8").digest("hex"),
      text: line.trimEnd(),
    }));

  return [category, messages];
})));

const names = new Set(defaultNames);
for (const line of humansFile.split("\n")) {
  if (!line.includes("Name:")) continue;

  const name = line.replace(/^.*Name: /, "");
  const github = name.indexOf("github");
  names.add(github >= 0 ? name.slice(github).replace(/^github:/, "").replace(/\)$/, "").trimEnd() : name.split(" ")[0]);
}

const output = `// Generated by scripts/build-data.mjs. Do not edit manually.\n\nexport type CommitMessage = {\n  readonly hash: string;\n  readonly text: string;\n};\n\nexport const messagesByCategory: Readonly<Record<string, readonly CommitMessage[]>> = ${JSON.stringify(messagesByCategory, null, 2)};\n\nexport const names: readonly string[] = ${JSON.stringify([...names], null, 2)};\n`;

await writeFile("src/data.generated.ts", output);
